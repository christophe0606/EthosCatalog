"""Shared graph conventions and generated configuration for this solution."""
from pathlib import Path
import argparse
import subprocess
import sys
from cmsis_stream.cg.scheduler import Configuration, Style


# Shared visual convention; applications explicitly select their driver nodes.
DRIVER_COLOR = '#8B4513'


class GraphStyle(Style):
    """White rectangles with application-supplied border and label colors.

    Keys are node instance names, including event-only nodes. The application
    owns the assignment, so styling never depends on scheduling order or on
    runtime properties such as needsHardware (which also applies to models).
    """

    def __init__(self, node_colors=None):
        super().__init__({'node_color': 'white', 'node_boundary_color': 'black'})
        self.node_colors = dict(node_colors or {})

    def node_boundary_color(self, node):
        return self.node_colors.get(node.nodeName, super().node_boundary_color(node))

    def node_label_color(self, node):
        return self.node_colors.get(node.nodeName, super().node_label_color(node))


def graph_only_requested():
    """Parse the common command-line option used by each project's app.py."""
    parser = argparse.ArgumentParser(description='Generate the CMSIS Stream application.')
    parser.add_argument('--graph-only', action='store_true',
                        help='Update only app.dot, app.png and app.pdf; preserve generated firmware files.')
    return parser.parse_args().graph_only


def render_graph(scheduling, output, config, style=None):
    """Render the scheduled graph without generating any firmware files."""
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    dot = output/'app.dot'
    with dot.open('w') as f:
        scheduling.graphviz(f, config=config, style=style if style is not None else GraphStyle())
    # The upstream DOT template leaves trailing spaces in edges.
    dot.write_text('\n'.join(line.rstrip() for line in dot.read_text().splitlines()) + '\n')
    # Render the same diagram as a PDF and a thumbnail bounded by 320 x 240 px.
    for format, options in (('pdf', []), ('png', ['-Gsize=4,3', '-Gdpi=80'])):
        try:
            subprocess.run(['dot', f'-T{format}', *options, str(dot),
                            '-o', str(output/f'app.{format}')],
                           check=True, capture_output=True, text=True)
        except (OSError, subprocess.CalledProcessError) as error:
            print(f'Warning: Graphviz {format.upper()} generation failed; app.dot is available: {error}', file=sys.stderr)

def configuration():
    conf = Configuration()
    conf.CMSISDSP = False
    conf.asynchronous = False
    conf.horizontal = True
    conf.nodeIdentification = True
    conf.schedName = "scheduler_app"
    conf.schedulerCFileName = "scheduler_app"
    conf.memoryOptimization = True
    conf.appConfigCName = "app_config.hpp"
    conf.appNodesCName = "AppNodes.hpp"
    conf.cOptionalInitArgs = ["AppParams *params"]
    conf.prefix = "stream_app_"
    return conf

def mk_app(graph, output, globals, runtime, config=None, source_notice='',
           style=None, graph_only=False):
    output = Path(output)
    output.mkdir(parents=True, exist_ok=True)
    conf = config or configuration()
    scheduling = graph.computeSchedule(config=conf)
    if graph_only:
        render_graph(scheduling, output, conf, style)
        return scheduling
    (output/'json').mkdir(exist_ok=True)
    nodes = scheduling.allNodes
    includes = sorted({f'{n.folder}/{n.typeName}.hpp' for n in nodes if hasattr(n, "folder")})
    (output / "AppNodes.hpp").write_text(source_notice + '// Generated by app.py.\n#pragma once\n' + ''.join(f'#include "{h}"\n' for h in includes))
    fields, initializers, members, hardware = [], [], [], []
    parameter_types = {}
    for node in nodes:
        params = getattr(node, 'params', {})
        hw = getattr(node, 'needsHardware', False)
        if not params and not hw:
            continue
        typename = node.typeName + 'Params'
        entries = ['    HardwareParams hw_;'] if hw else []
        entries += [f'    {"float" if isinstance(v, float) else "int32_t"} {k};' for k,v in params.items()]
        if typename in parameter_types and parameter_types[typename] != entries:
            raise ValueError(f'Inconsistent parameter layout for {typename}')
        if typename not in parameter_types:
            fields.append('typedef struct {\n' + '\n'.join(entries) + f'\n}} {typename};\n')
            parameter_types[typename] = entries
        members.append(f'    {typename} {node.nodeName};')
        values = [f'        .{k} = {v}{"f" if isinstance(v, float) else ""},' for k,v in params.items()]
        if hw:
            values.insert(0, '        .hw_ = {0},')
            hardware.append(f'    appParams.{node.nodeName}.hw_ = *params;')
        initializers.append(f'    .{node.nodeName} = {{\n' + '\n'.join(values) + '\n    },')
    banner = source_notice + '// Generated by app.py. Do not edit.\n'
    defines = ''.join(f'#define {k} {v}\n' for k,v in globals.items())
    (output/'app_sizes.h').write_text(banner + '#pragma once\n' + defines)
    (output/'stream_settings.h').write_text(banner + '#pragma once\n' + ''.join(f'#define {k} {v}\n' for k,v in runtime.items()))
    (output/'app_params.h').write_text(banner + '#pragma once\n#include <stdint.h>\n#include "app_sizes.h"\n#include "hardware_params.h"\n' + '\n'.join(fields) + '\ntypedef struct {\n' + '\n'.join(members) + '\n} AppParams;\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern AppParams appParams;\nvoid app_params_set_hardware(const HardwareParams *params);\n#ifdef __cplusplus\n}\n#endif\n')
    (output/'app_params.c').write_text(banner + '#include "app_params.h"\nAppParams appParams = {\n' + '\n'.join(initializers) + '\n};\nvoid app_params_set_hardware(const HardwareParams *params)\n{\n    if (!params) return;\n' + '\n'.join(hardware) + '\n}\n')
    scheduling.ccode(str(output), conf)
    scheduling.genJsonIdentification(str(output/'json'), conf)
    scheduling.genJsonSelectorsInit(str(output/'json'), conf)
    # The upstream templates leave trailing spaces in selectors.
    for name in ('scheduler_app.cpp', 'scheduler_app.h'):
        generated = output/name
        generated.write_text(source_notice + '\n'.join(line.rstrip() for line in generated.read_text().splitlines()) + '\n')
    render_graph(scheduling, output, conf, style)
    print(f'Schedule length = {scheduling.scheduleLength}; FIFO storage = {scheduling.memory} bytes')
    return scheduling
