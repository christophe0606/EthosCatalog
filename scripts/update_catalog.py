"""Generate README.md from documentation/readme_header.md and project YAML headers."""
from pathlib import Path
import sys
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parents[1]


def read_metadata(readme: Path) -> tuple[str, str]:
    lines = readme.read_text(encoding="utf-8-sig").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{readme}: README must start with a YAML header")
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        raise ValueError(f"{readme}: YAML header is missing its closing '---'")
    try:
        header = yaml.safe_load("\n".join(lines[1:end]))
    except yaml.YAMLError as error:
        raise ValueError(f"{readme}: invalid YAML header: {error}") from error
    metadata = {}
    for field in ("category", "description"):
        value = header.get(field) if isinstance(header, dict) else None
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{readme}: {field} must be a nonempty string")
        value = value.strip()
        if len(value.splitlines()) != 1:
            raise ValueError(f"{readme}: {field} must be a single line")
        metadata[field] = value
    return metadata["category"].lower(), metadata["description"]


def table_text(value: str) -> str:
    return value.replace("\\", "\\\\").replace("|", "\\|").replace("[", "\\[").replace("]", "\\]")


def update_catalog(root: Path = ROOT) -> Path:
    header = (root / "documentation/readme_header.md").read_text(encoding="utf-8-sig")
    categories = {}
    for project in (root / "projects").iterdir():
        if not project.is_dir():
            continue
        category, description = read_metadata(project / "README.md")
        categories.setdefault(category, []).append((project, description))

    rows = [
        "# Project catalog",
        "",
        "<!-- Generated by scripts/update_catalog.py from project README YAML headers. -->",
    ]
    for category in sorted(categories):
        rows.extend([
            "",
            f"## {table_text(category)}",
            "",
            "| Project name | Description | Benchmark |",
            "| --- | --- | --- |",
        ])
        for project, description in sorted(
            categories[category], key=lambda item: (item[0].name.casefold(), item[0].name)
        ):
            link = quote((project / "README.md").relative_to(root).as_posix(), safe="/")
            benchmark = project / "model/benchmark.yml"
            benchmark_link = (
                f"[benchmark.yml]({quote(benchmark.relative_to(root).as_posix(), safe='/')})"
                if benchmark.is_file() else "—"
            )
            rows.append(
                f"| [{table_text(project.name)}]({link}) | {table_text(description)} | {benchmark_link} |"
            )
    output = root / "README.md"
    output.write_text(header.rstrip() + "\n\n" + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    return output


def main() -> int:
    try:
        output = update_catalog()
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f"Updated {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
