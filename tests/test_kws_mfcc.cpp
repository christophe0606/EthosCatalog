#include "arm_math.h"
// Independently declared test-side backend contract and layout.
extern "C" {
typedef struct {
    uint32_t frame_samples,fft_length,mel_filters,features;
    const float *window,*filter_coefficients,*dct;
    const uint32_t *filter_positions,*filter_lengths;
    float log_floor;
} mfcc_config_t;
extern const mfcc_config_t kws_mfcc_config;
int mfcc_init(const mfcc_config_t*,arm_rfft_fast_instance_f32*);
void mfcc_compute(const mfcc_config_t*,const arm_rfft_fast_instance_f32*,const float*,float*,float*,float*,float*);
}
#include "MicroNetKwsMfcc.hpp"
#include <algorithm>
#include <array>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <vector>
static int quantize(float x) {
    return int(std::max(-128.f,std::min(127.f,std::round(x/0.20109497010707855f-5))));
}
int main(int argc,char **argv) {
    if(argc!=4) return 2;
    FILE* audio=std::fopen(argv[1],"rb");
    std::array<int16_t,16000> speech;
    if(!audio || std::fread(speech.data(),sizeof(int16_t),16000,audio)!=16000) return 3;
    std::fclose(audio);
    FILE* fixture=std::fopen(argv[2],"w");
    FILE* features=std::fopen(argv[3],"wb");
    if(!fixture || !features) return 4;
    std::fprintf(fixture,"// Copyright 2022 Arm Limited and/or its affiliates.\n// SPDX-License-Identifier: Apache-2.0\n// PCM from mlek-cmsis-pack-examples/kws/src/sample_audio.cpp (ks_down.wav).\n// Generated by tests/run_kws_tests.py against ML Eval Kit.\n#pragma once\n#include <stdint.h>\nstatic const int16_t kws_speech_pcm[16000]={\n");
    for(auto x:speech) std::fprintf(fixture,"%d,",int(x));
    std::fprintf(fixture,"\n};\nstatic const int8_t kws_speech_mfcc[490]={\n");
    arm::app::audio::MicroNetKwsMFCC reference(10,640);
    arm_rfft_fast_instance_f32 fft;
    if(mfcc_init(&kws_mfcc_config,&fft)) return 5;
    float frame[1024],spectrum[1026],mel[40],out[10],input[640];
    std::vector<int16_t> pcm(640);
    float max_error=0,stock_max_error=0; int max_lsb=0;
    unsigned frames=0,nonidentical=0;
    uint32_t rng=42;
    // Deterministic PCM patterns, including silence, quiet noise, impulses,
    // clipped input, tonal input and every frame of the reference speech clip.
    for(unsigned test=0;test<145;++test) {
        for(unsigned i=0;i<640;++i) {
            rng=1664525*rng+1013904223;
            int16_t x=int16_t(rng>>16);
            if(test==0) x=0;
            else if(test==1) x=2000;
            else if(test<5) x=i==test*101?30000:0;
            else if(test<15) x=int16_t(int(x)/(1<<((test-5)%10)));
            else if(test<47) x=int16_t(15000*std::sin(6.283185307179586*(test*67)*i/16000));
            else if(test<96) x=int16_t(int(x)/32);
            else x=speech[(test-96)*320+i];
            pcm[i]=x; input[i]=float(x)/32768.f;
        }
        auto expected=reference.MfccComputeQuant<int8_t>(pcm,0.20109497010707855f,-5);
        auto expected_float=reference.MfccCompute(pcm);
        mfcc_compute(&kws_mfcc_config,&fft,input,frame,spectrum,mel,out);
        for(unsigned i=0;i<10;++i) {
            max_error=std::max(max_error,std::fabs(out[i]-expected_float[i]));
            int diff=std::abs(quantize(out[i])-int(expected[i]));
            max_lsb=std::max(max_lsb,diff); nonidentical+=diff!=0;
            if(test>=96) {
                std::fprintf(fixture,"%d,",int(expected[i]));
                int8_t q=expected[i]; std::fwrite(&q,1,1,features);
            }
        }
        // The stock CMSIS-DSP log floor differs even with identical tables.
        for(unsigned i=0;i<40;++i)
            stock_max_error=std::max(stock_max_error,std::fabs(std::log(std::exp(mel[i])+1.e-6f)-mel[i]));
        ++frames;
    }
    std::fprintf(fixture,"\n};\n"); std::fclose(fixture); std::fclose(features);
    std::printf("MFCC: %u frames, max float error %.7g, max quantized error %d LSB, differing coefficients %u / %u\n",frames,max_error,max_lsb,nonidentical,frames*10);
    std::printf("Stock MFCC log floor divergence: %.6f natural-log units\n",stock_max_error);
    return max_lsb>1 ? 1 : 0;
}
