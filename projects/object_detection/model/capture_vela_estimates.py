"""Export compiler estimates and prove their command/weights equal the board PTE.

Does not replace the active ai_layer. Temporary compile metadata changes the PTE
container hash; the executable command stream and weights must remain identical.
"""
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import sys
import numpy as np
import yaml

ROOT=Path(__file__).resolve().parents[3]
MODEL=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'scripts'))
from quantized_model import compile_spec, load_quantized_program, sha256
from create_ai_layer import export_model
from validate_networks import load_network


def main():
    work=ROOT/'tmp/object_detection_vela';work.mkdir(parents=True,exist_ok=True)
    os.environ['TEMP']=str(ROOT/'tmp');os.environ['TMP']=str(ROOT/'tmp')
    network=load_network(MODEL/'network.yml')
    solution=yaml.safe_load((ROOT/'EthosCatalog.csolution.yml').read_text())['solution']
    program=load_quantized_program('ethos-u85-256',MODEL.parent,network)
    spec=compile_spec(solution,MODEL.parent,network).dump_intermediate_artifacts_to(str(work))
    pte,delegates=export_model(program,spec);assert delegates==1
    summaries=list(work.rglob('*summary*.csv'));assert len(summaries)==1
    shutil.copyfile(summaries[0],MODEL/'benchmark_vela_summary.csv')
    data=(ROOT/'ai_layer/model.pte').read_bytes()
    # This archive was generated by the export immediately above; object entries
    # are not loaded. Command and weight entries contain fixed byte strings.
    archive=np.load(work/'output/out_vela.npz',allow_pickle=False)
    position=data.index(b'vela_bin_stream\x00');blocks={}
    while True:
        name=data[position:position+16].rstrip(b'\x00').decode('ascii')
        length=struct.unpack_from('<I',data,position+16)[0]
        payload=data[position+32:position+32+length]
        if name in ('cmd_data','weight_data'):
            expected=archive[name].tobytes()
            blocks[name]={'pte_bytes':length,'estimate_bytes':len(expected),
                          'pte_sha256':hashlib.sha256(payload).hexdigest(),
                          'estimate_sha256':hashlib.sha256(expected).hexdigest(),'identical':payload==expected}
            assert payload==expected,name
        position+=32+(length+15)//16*16
        if name=='vela_end_stream':break
    report={'board_pte_sha256':sha256(ROOT/'ai_layer/model.pte'),
            'estimate_container_sha256':hashlib.sha256(pte).hexdigest(),
            'estimate_container_bytes':len(pte),'summary_sha256':sha256(MODEL/'benchmark_vela_summary.csv'),
            'blocks':blocks,'scope':'Compiler estimates; identical executable streams, different export metadata container'}
    (MODEL/'benchmark_vela_provenance.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))


if __name__=='__main__':
    main()
