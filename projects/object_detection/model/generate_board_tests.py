"""Generate four small board fixtures with both source heads and PyTorch outputs."""
import argparse
import json
from pathlib import Path
import sys
import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from project_config import selected_project
from quantized_model import load_quantized_program, sha256
from patterns import patterns, SEED
from model import SOURCE
from validate import reference


def matrix(name, values):
    values = values.reshape(len(values), -1)
    rows = []
    for row in values:
        chunks = [",".join(map(str, row[i:i+24].tolist())) for i in range(0, len(row), 24)]
        rows.append("  {\n    " + ",\n    ".join(chunks) + "\n  }")
    return f"static const int8_t {name}[{values.shape[0]}][{values.shape[1]}] = {{\n" + ",\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-python", type=Path, required=True)
    args = parser.parse_args()
    torch.set_num_threads(4)
    _, solution, project, _, network = selected_project(project="object_detection")
    npu = solution["mlops"]["npu"]
    program = load_quantized_program(f"{npu['type'].lower()}-{npu['macs']}", project.parent, network)
    all_names, all_inputs = patterns()
    names = ["source_sample", "constant_-128", "horizontal_ramp", "random_0"]
    inputs = all_inputs[[all_names.index(name) for name in names]]
    references = reference(inputs, args.reference_python)
    with torch.no_grad():
        outputs = [program.module()(torch.from_numpy(x)) for x in inputs]
    header = ("// Copyright 2026 Arm Limited and/or its affiliates.\n"
              "// SPDX-License-Identifier: Apache-2.0\n"
              "// Generated by model/generate_board_tests.py; do not edit.\n"
              "// Source sample: Copyright 2022 Arm Limited and/or its affiliates. Apache-2.0.\n"
              "#pragma once\n#include <stdint.h>\n"
              "constexpr unsigned DETECTION_TEST_CASES = 4;\n"
              "constexpr unsigned DETECTION_INPUT_ELEMENTS = 36864;\n"
              "constexpr unsigned DETECTION_OUTPUT0_ELEMENTS = 648;\n"
              "constexpr unsigned DETECTION_OUTPUT1_ELEMENTS = 2592;\n"
              "constexpr unsigned DETECTION_BENCHMARK_CASE = 3; // random_0\n"
              "constexpr unsigned DETECTION_BENCHMARK_SAMPLES = 100;\n"
              "// Initial board-vs-default gate; independently report each head and decoded source faces.\n"
              "constexpr unsigned DETECTION_TOLERANCE_LSB = 8;\n")
    header += matrix("detection_test_inputs", inputs)
    payload = {}
    for i in range(2):
        for mode in ("default", "reference"):
            array = references[f"{mode}_{i}"]
            header += matrix(f"detection_tflite_{mode}{i}", array)
            payload[f"{mode}_{i}"] = array.reshape(len(names), -1).tolist()
        array = np.stack([out[i].numpy() for out in outputs])
        header += matrix(f"detection_pytorch{i}", array)
        payload[f"pytorch_{i}"] = array.reshape(len(names), -1).tolist()
    dest = Path(__file__).parent
    (dest / "model_test_data.h").write_text(header, encoding="utf-8", newline="\n")
    report = {"seed": SEED, "patterns": names, "benchmark_pattern": "random_0", "benchmark_case": 3,
              "source_sha256": sha256(SOURCE), "graph_sha256": sha256(project.parent/network["graph"]),
              "safetensors_sha256": sha256(project.parent/network["safetensors"]),
              "header_sha256": sha256(dest / "model_test_data.h"), "generator_sha256": sha256(Path(__file__)),
              "tensorflow": str(references["tensorflow_version"]), "torch": torch.__version__,
              "output_layout": "NHWC", "output_shapes": [[1,6,6,18], [1,12,12,18]],
              "initial_board_default_tolerance_lsb": 8, "compiled_constant_bytes": 4*(36864+3*(648+2592)),
              "expected": payload}
    (dest / "board_test_vectors.json").write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    print(f"Generated {len(names)} board patterns: {names}; {report['compiled_constant_bytes']} constant bytes")


if __name__ == "__main__":
    main()
