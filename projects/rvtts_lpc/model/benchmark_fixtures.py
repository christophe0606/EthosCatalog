"""Create held-out complete-schedule fixtures without changing model caches."""
from pathlib import Path
import numpy as np
import torch
from model import method_models,run_methods,sample

def declaration(name,array,ctype):
    flat=np.asarray(array).reshape(-1)
    values=[f"{float(x):.9e}f" if ctype=="float" else str(int(x)) for x in flat]
    rows=[",".join(values[i:i+16]) for i in range(0,len(values),16)]
    return f"static const {ctype} {name}[{len(values)}]={{\n"+",\n".join(rows)+"\n};"

def main():
    torch.set_num_threads(1)
    models=method_models()
    lines=["// Copyright 2026 Arm Limited and/or its affiliates.","// SPDX-License-Identifier: Apache-2.0",
           "// Generated by benchmark_fixtures.py; reference is supplied int8 weights with float activations.","#pragma once","#include <cstdint>"]
    for n,seed in ((2,800),(81,802),(157,803)):
        data=sample(seed,n)
        with torch.no_grad(): features,_=run_methods(models,*data)
        for suffix,array,ctype in (("phones",data[0],"uint8_t"),("stress",data[1],"uint8_t"),("words",data[2],"uint16_t"),("features",features.numpy(),"float")):
            lines.append(declaration(f"rvtts_sequence_{n}_{suffix}",array,ctype))
    Path(__file__).with_name("benchmark_inputs.h").write_text("\n".join(lines)+"\n",encoding="utf-8")

if __name__=="__main__":main()
