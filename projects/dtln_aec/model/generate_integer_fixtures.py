"""Generate independent board expectations with the integer TOSA reference model.

Reuse the deployment compile specification and automatic Ethos partitioning.
Capture each delegate immediately before Vela and execute its serialized TOSA
with the installed reference model. CPU operators execute in PyTorch. The
deployment PTE, quantized caches and original PTQ fixtures are read-only inputs.
"""
import argparse
from contextlib import contextmanager
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import sys
import tempfile
from unittest.mock import patch

import numpy as np
import torch
from torch.overrides import TorchFunctionMode

MODEL = Path(__file__).resolve().parent
ROOT = MODEL.parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from project_config import selected_project
from quantized_model import compile_spec, load_quantized_program, method_configs
from executorch.backends.arm.ethosu.backend import EthosUBackend
from executorch.backends.arm.ethosu import EthosUPartitioner
from executorch.backends.arm.test.runner_utils import run_tosa_graph
from executorch.exir import EdgeCompileConfig, to_edge_transform_and_lower


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


@contextmanager
def repository_scratch():
    scratch = ROOT / "tmp"
    scratch.mkdir(exist_ok=True)
    previous = tempfile.tempdir
    tempfile.tempdir = str(scratch)
    try:
        yield
    finally:
        tempfile.tempdir = previous


class IntegerReferenceDispatch(TorchFunctionMode):
    def __init__(self, tosa_spec):
        super().__init__()
        self.tosa_spec = tosa_spec

    def __torch_function__(self, function, types, args=(), kwargs=None):
        if function is torch._higher_order_ops.executorch_call_delegate:
            module = args[0]
            return tuple(run_tosa_graph(
                module.processed_bytes, self.tosa_spec, args[1:],
                module.original_module.graph.output_node()))
        return function(*args, **(kwargs or {}))


def errors(actual, expected):
    difference = np.abs(actual.astype(np.float64) - expected.astype(np.float64))
    return {
        "max_absolute_error": float(difference.max()),
        "mean_absolute_error": float(difference.mean()),
        "root_mean_square_error": float(np.sqrt(np.mean(difference**2))),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--board-captures-dir", type=Path,
                        help="Optional directory containing board_sram_stage1.json and stage2.json")
    args = parser.parse_args()
    _, solution, project, config, network = selected_project(project="dtln_aec")
    assert project.parent == MODEL.parent
    torch.set_num_threads(1)
    spec = compile_spec(solution, project.parent, network)
    fixtures_path = MODEL / "method_fixtures.npz"
    fixtures = np.load(fixtures_path)
    manifest = json.loads((project.parent / "ai_layer/generation.json").read_text())
    assert manifest["config_sha256"] == digest(config)
    pte_path = project.parent / "ai_layer/model.pte"
    assert manifest["pte_sha256"] == digest(pte_path)
    report = {
        "reference": "Integer TOSA immediately before Vela using the deployment Ethos partitions",
        "pte_sha256": manifest["pte_sha256"],
        "fixture_inputs_sha256": digest(fixtures_path),
        "versions": {name: version(name) for name in ("torch", "executorch", "tosa-tools")},
        "tosa_specification": str(spec.tosa_spec),
        "methods": {},
    }
    header = [
        "// Copyright 2026 Arm Limited and/or its affiliates.",
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by model/generate_integer_fixtures.py.",
        "// Inputs are the stage input arrays in model_test_data.h.",
        "#pragma once",
    ]
    for name, settings in method_configs(network).items():
        cache = manifest["method_caches"][name]
        assert cache["graph_sha256"] == digest(project.parent / settings["graph"])
        assert cache["safetensors_sha256"] == digest(project.parent / settings["safetensors"])
        program = load_quantized_program(spec.target, project.parent, settings)
        inputs = tuple(torch.from_numpy(fixtures[f"{name}_input{i}"].copy()) for i in range(3))
        tosa_hashes = []

        def retain_tosa(graph, unused_compile_spec):
            tosa_hashes.append(hashlib.sha256(graph).hexdigest())
            return graph

        # This process-local interception keeps the ordinary Ethos partitioner
        # and preprocessing. The intercepted bytes are never serialized as a PTE.
        with repository_scratch(), patch.object(
                EthosUBackend, "_compile_tosa_flatbuffer", staticmethod(retain_tosa)):
            edge = to_edge_transform_and_lower(
                program, partitioner=[EthosUPartitioner(spec)],
                compile_config=EdgeCompileConfig(_check_ir_validity=False))
        delegate_calls = sum(node.op == "call_function" and "executorch_call_delegate" in str(node.target)
                             for node in edge.exported_program().graph.nodes)
        assert delegate_calls and tosa_hashes
        with torch.no_grad(), IntegerReferenceDispatch(spec.tosa_spec):
            actual = edge.exported_program().module(check_guards=False)(*inputs)
        header.append(f"#define DTLN_{name.upper()}_DELEGATES {delegate_calls}U")
        method_report = {"cache_sha256": cache, "delegate_calls": delegate_calls,
                         "tosa_sha256": tosa_hashes, "outputs": {}}
        board = None
        if args.board_captures_dir:
            capture = args.board_captures_dir / f"board_sram_{name}.json"
            board = json.loads(capture.read_text())
            method_report["board_capture_sha256"] = digest(capture)
        for index, tensor in enumerate(actual):
            values = tensor.detach().numpy().reshape(-1)
            assert np.isfinite(values).all()
            expected_ptq = fixtures[f"{name}_output{index}"].reshape(-1)
            entry = {"elements": len(values), "integer_vs_prevela_ptq": errors(values, expected_ptq)}
            if board is not None:
                captured = np.asarray(board[f"output{index}"], np.float32)
                assert captured.shape == values.shape
                entry["board_vs_integer_reference"] = {
                    **errors(captured, values),
                    "different_float32_values": int(np.count_nonzero(captured != values)),
                }
            method_report["outputs"][f"output{index}"] = entry
            header.append(f"static const float {name}_integer_output{index}[{len(values)}] = {{")
            for offset in range(0, len(values), 8):
                header.append("    " + ", ".join(f"{float(value):.9e}f"
                    for value in values[offset:offset + 8]) + ",")
            header.append("};")
        report["methods"][name] = method_report
        print(name, json.dumps(method_report), flush=True)
    assert digest(pte_path) == manifest["pte_sha256"]
    (MODEL / "integer_test_data.h").write_text("\n".join(header) + "\n", encoding="utf-8", newline="\n")
    (MODEL / "integer_fixture_validation.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
