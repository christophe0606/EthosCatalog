"""Generate two independently replayable board vectors from the saved PTQ graph.

One silent cold-state input and one speech frame with a nonzero preceding state.
Replay each with the supplied h/c, including every benchmark repetition. Live
capture instead propagates returned h/c and carries64 prior PCM samples.
"""
import json,sys
from pathlib import Path
import torch,yaml
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'scripts'))
from quantized_model import load_quantized_program,save_quantized_program
from model import SileroVAD
from quantize import waveform,frames

def main():
    torch.set_num_threads(1)
    project=Path(__file__).resolve().parents[1]
    network=yaml.safe_load((project/'model/network.yml').read_text())['network']
    program=load_quantized_program('ethos-u85-256',project,network)
    quantized=program.module(check_guards=False)
    model=SileroVAD().eval()
    zero=torch.zeros(1,128)
    vectors=[(torch.zeros(1,576),zero.clone(),zero.clone())]
    h=zero.clone();c=zero.clone()
    with torch.no_grad():
        for x in frames(waveform()[:480000]):
            probability,nh,nc=model(x,h,c)
            if probability.item()>.95:
                vectors.append((x,h,c));break
            h,c=nh,nc
    assert len(vectors)==2
    outputs=[]
    with torch.no_grad():
        for v in vectors:outputs.append(quantized(*v))
    lines=['// Copyright 2026 Arm Limited and/or its affiliates.',
           '// SPDX-License-Identifier: Apache-2.0',
           '// Generated by model/generate_test_data.py from pinned MIT Silero weights/audio.',
           '#pragma once','#define SILERO_TEST_COUNT 2U',
           '// Inputs/outputs are float32. One cold silence and one warm-state speech frame.',
           'static constexpr float silero_test_probability_tolerance=0.04f;',
           'static constexpr float silero_test_state_tolerance=0.12f;']
    def array(name,values):
        count=values[0].numel();lines.append(f'static const float {name}[SILERO_TEST_COUNT][{count}] = {{')
        for v in values:
            numbers=[format(float(x),'.9e')+'f' for x in v.flatten()]
            lines.append('  {')
            for i in range(0,len(numbers),8):lines.append('    '+', '.join(numbers[i:i+8])+',')
            lines.append('  },')
        lines.append('};')
    for i,key in enumerate(('audio','h','c')):array('silero_test_'+key,[v[i] for v in vectors])
    for i,key in enumerate(('probability','h','c')):array('silero_test_expected_'+key,[v[i] for v in outputs])
    (project/'model/model_test_data.h').write_text('\n'.join(lines)+'\n')
    print('Board vector PTQ probabilities:',[v[0].item() for v in outputs],flush=True)
    # Bind safetensors metadata to the final quantizer source without changing graph content.
    save_quantized_program(program,'ethos-u85-256',project,network)

if __name__=='__main__':main()
