"""Independent double-precision NumPy CPU gate/window fixtures for the MCU."""
from pathlib import Path
import numpy as np

def main():
    rng=np.random.default_rng(9124)
    gates=rng.normal(size=1600).astype(np.float32)
    c=rng.normal(size=400).astype(np.float32)
    i,j,f,o=np.split(gates.astype(np.float64),4)
    sigmoid=lambda x: 1/(1+np.exp(-x))
    new_c=sigmoid(f+1)*c+sigmoid(i)*np.tanh(j)
    h=np.tanh(new_c)*sigmoid(o)
    attention=rng.normal(size=30).astype(np.float32)
    kappa=rng.uniform(0,2,size=10).astype(np.float32)
    positive=np.logaddexp(0,attention.astype(np.float64))
    alpha,beta,delta=np.split(positive,3)
    positions=kappa+delta/25
    phi=(alpha[:,None]*np.exp(-(positions[:,None]-np.arange(4)[None,:])**2/np.maximum(beta[:,None],.01))).sum(0)
    window=np.zeros(73); np.add.at(window,[40,2,40,0],phi)
    arrays=dict(cpu_cell_gates=gates,cpu_cell_c=c,cpu_cell_h_expected=h,
                cpu_cell_c_expected=new_c,cpu_window_attention=attention,
                cpu_window_kappa=kappa,cpu_phi_expected=phi,cpu_window_expected=window)
    text='// Generated by make_cpu_test_data.py.\n// SPDX-License-Identifier: Apache-2.0\n#pragma once\n'
    for name,a in arrays.items():
        text+=f'static const float {name}[{a.size}]={{'+','.join(f'{v:.9e}f' for v in a)+'};\n'
    Path(__file__).with_name('cpu_test_data.h').write_text(text)

if __name__=='__main__': main()
