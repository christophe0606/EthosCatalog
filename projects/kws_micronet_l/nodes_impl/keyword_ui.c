const char *kws_label(unsigned i) {
    static const char *const labels[]={"DOWN","GO","LEFT","NO","OFF","ON","RIGHT","STOP","UP","YES","SILENCE","UNKNOWN"};
    return i<12 ? labels[i] : "";
}
static void text(uint16_t *fb,const char *s,unsigned y,unsigned scale,uint16_t color) {
    unsigned x=(800-strlen(s)*6*scale)/2;
    for (;*s;++s,x+=6*scale) {
        if (*s<'A' || *s>'Z') continue;
        for(unsigned c=0;c<5;++c) for(unsigned r=0;r<7;++r)
            if(letters[*s-'A'][c]&(1U<<r))
                for(unsigned dx=0;dx<scale;++dx) for(unsigned dy=0;dy<scale;++dy)
                    fb[(x+c*scale+dx)*480+479-(y+r*scale+dy)]=color;
    }
}
void keyword_render(uint16_t *fb,unsigned word,unsigned alpha) {
    memset(fb,0,800*480*sizeof(uint16_t));
    text(fb,"MICRONET KEYWORD SPOTTING",58,3,0x7bef);
    text(fb,"SAY A COMMAND",390,2,0x7bef);
    if(alpha>255) alpha=255;
    uint16_t color=(uint16_t)(((5*alpha/255)<<11)|((63*alpha/255)<<5)|(25*alpha/255));
    if(word<10 && alpha) text(fb,kws_label(word),205,8,color);
}
