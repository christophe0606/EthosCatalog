"""Generate project tables using CMSIS-DSP Scripts/mfccdata.py and YAML."""
from pathlib import Path
import argparse, sys, yaml, re
import numpy as np

def generate(scripts):
    sys.path.insert(0,str(Path(scripts).resolve()))
    import mfccdata as gen
    here = Path(__file__).resolve().parent
    c = yaml.safe_load((here/'mfcc_config.yaml').read_text())
    gen.prepareDctconfig(c['dct'])
    gen.prepareMelconfig(c['melfilter'])
    gen.prepareWindowConfig(c['window'])
    d,m,w = c['dct']['kws'],c['melfilter']['kws'],c['window']['kws']
    # ML Eval Kit on Cortex-M uses arm_cos_f32 for its window and DCT.
    # Its table interpolation differs measurably from exact scipy cosines for
    # tonal input. Reproduce it with the DSP sine table and float32 operations.
    source=(Path(scripts).resolve().parent/'Source/CommonTables/arm_common_tables.c').read_text()
    raw=re.search(r'const float32_t sinTable_f32\[[^;]+?=\s*\{([^}]+)',source,re.S).group(1)
    sine=np.array([float(x.strip().rstrip('fF')) for x in raw.split(',') if x.strip()],dtype=np.float32)
    f=np.float32
    def cosine(x):
        v=f(f(f(x)*f(0.159154943092))+f(0.25))
        n=int(v)-(1 if v<0 else 0)
        index_float=f(f(v-f(n))*f(512))
        index=int(index_float)
        if index>=512: index=0; index_float=f(index_float-f(512))
        fract=f(index_float-f(index))
        return f(f(f(1-fract)*sine[index])+f(fract*sine[index+1]))
    multiplier=f(2*float(f(np.pi))/w['frameLength'])
    window=[f(0.5-0.5*float(cosine(f(i)*multiplier))) for i in range(w['frameLength'])]
    angle=f(0); increment=f(float(f(np.pi))/d['melFilters']); normalizer=f(np.sqrt(f(2/d['melFilters'])))
    dct=[]
    for k in range(d['dctOutputs']):
        dct.extend([f(normalizer*cosine(f(f(n+0.5)*angle))) for n in range(d['melFilters'])])
        angle=f(angle+increment)
    _,_,_,filters,_=gen.melFilterMatrix(m['fmin'],m['fmax'],m['melFilters'],m['samplingRate'],m['fftlength'])
    def floats(values): return '{\n'+','.join(f'{float(f(x)):.9e}f' for x in values)+'\n}'
    arrays = [('float','kws_window',floats(window)),
              ('float','kws_filter',floats(filters)),('float','kws_dct',floats(dct)),
              ('uint32_t','kws_filter_pos',m['filtPosArray']),
              ('uint32_t','kws_filter_len',m['filtLenArray'])]
    text = '// Generated by generate_mfcc.py from mfcc_config.yaml.\n#include "../../../common/nodes_impl/c/MFCC.hpp"\n#include "mfcc_tables.h"\n#include <float.h>\n'
    for dtype,name,data in arrays:
        text += f'static const {dtype} {name}[] = {data};\n'
    text += (f'const mfcc_config_t kws_mfcc_config = {{{w["frameLength"]},{m["fftlength"]},{m["melFilters"]},{d["dctOutputs"]},'
             'kws_window,kws_filter,kws_dct,kws_filter_pos,kws_filter_len,FLT_MIN};\n')
    (here/'generated/mfcc_tables.c').write_text(text)
    (here/'generated/mfcc_tables.h').write_text('// Generated by generate_mfcc.py.\n#pragma once\ntypedef struct mfcc_config mfcc_config_t;\n#ifdef __cplusplus\nextern "C" {\n#endif\nextern const mfcc_config_t kws_mfcc_config;\n#ifdef __cplusplus\n}\n#endif\n')

if __name__ == '__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--dsp-scripts',required=True)
    generate(p.parse_args().dsp_scripts)
