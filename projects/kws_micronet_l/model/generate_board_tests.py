"""Generate local synthetic int8 test vectors and independent host references."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts"))
from project_config import selected_project
from quantized_model import load_quantized_program, sha256
from fake_inputs import fake_inputs, SEED
from model import SOURCE


def matrix(name, values):
    values = values.reshape(len(values), -1)
    rows = ["  {" + ",".join(map(str, row.tolist())) + "}" for row in values]
    return f"static const int8_t {name}[{values.shape[0]}][{values.shape[1]}] = {{\n" + ",\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-python", type=Path, required=True)
    args = parser.parse_args()
    torch.set_num_threads(4)
    _, solution, project, _, network = selected_project(project="kws_micronet_l")
    npu = solution["mlops"]["npu"]
    program = load_quantized_program(f"{npu['type'].lower()}-{npu['macs']}", project.parent, network)
    names, inputs = fake_inputs()
    (ROOT / "tmp").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="kws-board-vectors-", dir=ROOT / "tmp") as directory:
        temp = Path(directory)
        np.save(temp / "inputs.npy", inputs)
        subprocess.run([str(args.reference_python.resolve()), str(Path(__file__).with_name("tflite_reference.py")),
                        "--source", str(SOURCE), "--inputs", str(temp / "inputs.npy"),
                        "--outputs", str(temp / "outputs.npz")], check=True,
                       env=dict(os.environ, TF_CPP_MIN_LOG_LEVEL="2"))
        with np.load(temp / "outputs.npz", allow_pickle=False) as values:
            reference = values["reference"].copy()
            default = values["default"].copy()
            tf_version = str(values["tensorflow_version"])
    module = program.module()
    with torch.no_grad():
        pytorch = np.stack([module(torch.from_numpy(x)).numpy() for x in inputs])
    assert np.abs(pytorch.astype(int)-default.astype(int)).max() <= 1
    assert np.abs(pytorch.astype(int)-reference.astype(int)).max() <= 2
    header = ("// Generated by model/generate_board_tests.py; do not edit.\n"
              "#pragma once\n#include <stdint.h>\n"
              f"constexpr unsigned KWS_TEST_CASES = {len(inputs)};\n"
              "constexpr unsigned KWS_INPUT_ELEMENTS = 490;\n"
              "constexpr unsigned KWS_OUTPUT_ELEMENTS = 12;\n"
              "constexpr unsigned KWS_BENCHMARK_CASE = 14; // random_0, full int8 range\n"
              "constexpr unsigned KWS_BENCHMARK_SAMPLES = 100;\n"
              "constexpr unsigned KWS_TOLERANCE_LSB = 2;\n")
    header += matrix("kws_test_inputs", inputs)
    header += matrix("kws_tflite_default", default)
    header += matrix("kws_tflite_reference", reference)
    header += matrix("kws_pytorch", pytorch)
    output = Path(__file__).with_name("model_test_data.h")
    output.write_text(header, encoding="utf-8", newline="\n")
    report = {"seed": SEED, "patterns": names, "benchmark_pattern": names[14],
              "source_sha256": sha256(SOURCE), "graph_sha256": sha256(project.parent/network["graph"]),
              "safetensors_sha256": sha256(project.parent/network["safetensors"]),
              "header_sha256": sha256(output), "generator_sha256": sha256(Path(__file__)),
              "tensorflow": tf_version, "torch": torch.__version__, "tolerance_lsb": 2}
    Path(__file__).with_name("board_test_vectors.json").write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    print(f"Generated {len(inputs)} local patterns and TFLite/PyTorch references: {output}", flush=True)


if __name__ == "__main__":
    main()
