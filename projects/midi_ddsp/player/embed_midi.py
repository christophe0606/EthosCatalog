"""Embed a Standard MIDI File as score events, never as rendered audio."""
from pathlib import Path
import argparse

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('midi',type=Path)
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'assets/demo_midi.h')
    args=parser.parse_args()
    data=args.midi.read_bytes()
    if data[:4]!=b'MThd':
        parser.error('input must be a Standard MIDI File')
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text('// Copyright 2026 Arm Limited and/or its affiliates.\n'
                           '// SPDX-License-Identifier: Apache-2.0\n'
                           '// Generated by player/embed_midi.py. Score bytes, no audio samples.\n'
                           '#pragma once\n#include <stdint.h>\nstatic const uint8_t midi_demo_file[]={\n'+
                           '\n'.join(','.join(str(v) for v in data[i:i+24])+',' for i in range(0,len(data),24))+'\n};\n')
    print(f'Embedded {len(data)} MIDI bytes in {args.output}')

if __name__=='__main__':main()
