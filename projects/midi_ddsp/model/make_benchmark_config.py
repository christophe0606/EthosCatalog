"""Generate firmware fixture shapes/offsets from the programmed asset manifest."""
import argparse
import json
import math
from pathlib import Path

METHODS = ["expression_forward", "expression_backward", "expression_step",
           "precondition", "context_forward", "context_backward", "pitch_step", "harmonic"]
# Explicit existing provisional gates; generation does not relax acceptance.
TOLERANCE = [0.005] * 6 + [0.00769939423, 0.0119089603]

def main():
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixtures", type=Path, default=here / "benchmark_fixtures.json")
    parser.add_argument("--output", type=Path, default=here / "benchmark_config.h")
    args = parser.parse_args()
    data = json.loads(args.fixtures.read_text())
    lines = ["// Copyright 2026 Arm Limited and/or its affiliates.",
             "// SPDX-License-Identifier: Apache-2.0", "#pragma once",
             "// Generated by make_benchmark_config.py from benchmark_fixtures.json.",
             "struct MidiMethodFixture {const char *name;unsigned input_offset,input_count,output_offset,output_count,rank;int shape[3];float tolerance;};",
             "static const MidiMethodFixture midi_fixtures[]={"]
    for name, tolerance in zip(METHODS, TOLERANCE):
        method = data["methods"][name]
        source, expected = method["input"], method["expected"]
        shape = source["shape"]
        if not 1 <= len(shape) <= 3 or any(int(n) <= 0 for n in shape):
            raise ValueError(f"Invalid input shape for {name}: {shape}")
        for tensor in [source, expected]:
            if math.prod(tensor["shape"]) != tensor["count"]:
                raise ValueError(f"Invalid tensor count for {name}")
            if tensor["offset"] % 32 or tensor["offset"] + 4*tensor["count"] > data["bytes"]:
                raise ValueError(f"Invalid fixture range/alignment for {name}")
        padded = shape + [0] * (3-len(shape))
        lines.append('{"%s",%d,%d,%d,%d,%d,{%s},%.11gf},' %
                     (name, source["offset"], source["count"], expected["offset"],
                      expected["count"], len(shape), ",".join(map(str, padded)), tolerance))
    lines += ["};", ""]
    args.output.write_text("\n".join(lines))
    print(f"Generated {len(METHODS)} fixture entries: {args.output.name}")

if __name__ == "__main__":
    main()
