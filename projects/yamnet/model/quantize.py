"""YAMNet static PTQ; train-free synthetic waveform calibration and held-out tests."""
import argparse, json, sys
from pathlib import Path
import numpy as np
import torch
import yaml
from model import YAMNet
ROOT=Path(__file__).resolve().parents[3]
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/'scripts'))
from project_config import DEFAULT_SOLUTION, selected_project
from quantized_model import compile_spec, save_quantized_program


def c_array(name, values):
    flat=np.asarray(values).ravel()
    rows=[', '.join(f'{float(v):.9e}f' for v in flat[i:i+8]) for i in range(0,len(flat),8)]
    return f'static const float {name}[{len(flat)}] = {{\n  '+',\n  '.join(rows)+'\n};\n'


def write_firmware_fixtures(evaluation, outputs, cases):
    ref=evaluation['scores'];assert 0<cases<=len(ref)
    # Firmware fixtures retain distinct original-float and pre-Vela PTQ outputs.
    header=f'// Copyright 2026 Arm Limited and/or its affiliates.\n// SPDX-License-Identifier: Apache-2.0\n// Generated by quantize.py. Row-major [1,96,64] input, 521 sigmoid scores.\n#pragma once\n#define YAMNET_TEST_CASES {cases}U\n#define YAMNET_INPUT_SIZE 6144U\n#define YAMNET_OUTPUT_SIZE 521U\n'
    for i in range(cases):
        header+=c_array(f'yamnet_test_input_{i}',evaluation['inputs'][i])+c_array(f'yamnet_test_quantized_{i}',outputs[i])+c_array(f'yamnet_test_float_{i}',ref[i])
    header+=f'static const float *const yamnet_test_inputs[{cases}] = {{'+', '.join(f'yamnet_test_input_{i}' for i in range(cases))+'};\n'
    header+=f'static const float *const yamnet_test_quantized[{cases}] = {{'+', '.join(f'yamnet_test_quantized_{i}' for i in range(cases))+'};\n'
    header+=f'static const float *const yamnet_test_float[{cases}] = {{'+', '.join(f'yamnet_test_float_{i}' for i in range(cases))+'};\n'
    (HERE/'model_test_data.h').write_text(header)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--solution',type=Path,default=DEFAULT_SOLUTION)
    parser.add_argument('--project',default='yamnet')
    parser.add_argument('--activation',choices=['int8','int16'],default='int16')
    parser.add_argument('--depthwise-activation',choices=['int8','int16','float'],default='float')
    parser.add_argument('--depthwise-implementation',choices=['depthwise','dense'],default='depthwise')
    parser.add_argument('--first-conv-activation',choices=['int8','int16','float'],default='float')
    parser.add_argument('--firmware-cases',type=int,default=40)
    parser.add_argument('--fixtures-only',action='store_true')
    args=parser.parse_args()
    if args.fixtures_only:
        write_firmware_fixtures(np.load(HERE/'evaluation_reference.npz'),np.load(HERE/'evaluation_quantized.npz')['scores'],args.firmware_cases)
        return
    _,solution,project,_,network=selected_project(args.solution,args.project)
    assert project.parent==HERE.parent
    torch.set_num_threads(1)
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_a16w8_quantization_config, get_symmetric_quantization_config
    from torchao.quantization.pt2e.quantize_pt2e import prepare_pt2e, convert_pt2e
    spec=compile_spec(solution,project.parent,network)
    calib=np.load(HERE/'calibration_reference.npz'); evaluation=np.load(HERE/'evaluation_reference.npz')
    model=YAMNet(depthwise_implementation=args.depthwise_implementation).eval()
    with torch.no_grad():
        float_outputs=np.concatenate([model(torch.from_numpy(x[None].copy())).numpy() for x in evaluation['inputs']])
    float_variant_error=float(np.max(np.abs(float_outputs-evaluation['scores'])))
    assert float_variant_error < 1e-4, float_variant_error
    example=(torch.from_numpy(calib['inputs'][:1].copy()),)
    graph=torch.export.export(model,example).module(check_guards=False)
    config=(get_symmetric_a16w8_quantization_config if args.activation=='int16' else get_symmetric_quantization_config)(is_per_channel=True)
    quantizer=EthosUQuantizer(spec).set_global(config)
    if args.first_conv_activation=='int8' and args.activation=='int16':
        quantizer.set_module_name('blocks.0',get_symmetric_quantization_config(is_per_channel=True))
    if args.first_conv_activation=='float':
        quantizer.set_module_name('blocks.0',None)
    if args.depthwise_activation in ['int8','float']:
        for index,block in enumerate(model.blocks):
            if block.conv.groups>1:
                quantizer.set_module_name(f'blocks.{index}', None if args.depthwise_activation=='float' else get_symmetric_quantization_config(is_per_channel=True))
    prepared=prepare_pt2e(graph,quantizer)
    with torch.no_grad():
        for x in calib['inputs']:
            prepared(torch.from_numpy(x[None].copy()))
    quantized=convert_pt2e(prepared,fold_quantize=True)
    outputs=[]
    with torch.no_grad():
        for x in evaluation['inputs']:
            outputs.append(quantized(torch.from_numpy(x[None].copy())).numpy()[0])
    outputs=np.array(outputs); ref=evaluation['scores']; err=np.abs(outputs-ref)
    ref_top5=np.argsort(ref,axis=1)[:,-5:]
    quant_top5=np.argsort(outputs,axis=1)[:,-5:]
    independent=[1]+list(range(3,len(outputs)))
    report={'reference':'official pinned Keras YAMNet on 38 independently seeded synthetic patterns plus shared silence/440Hz controls',
            'activation':args.activation,'depthwise_activation':args.depthwise_activation,
            'depthwise_implementation':args.depthwise_implementation,'float_variant_max_abs_error':float_variant_error,
            'first_conv_activation':args.first_conv_activation,
            'weights':'int8 per output channel for quantized pointwise/head; float32 first/depthwise when excluded',
            'partition_policy':'Automatic EthosUPartitioner; unquantized float spatial modules use CPU fallback',
            'calibration_patterns':len(calib['inputs']),
            'evaluation_patterns':len(outputs),'calibration_seed':51773,'evaluation_seed':19429,
            'mean_absolute_score_error':float(err.mean()),'max_absolute_score_error':float(err.max()),
            'top1_agreement':float(np.mean(outputs.argmax(1)==ref.argmax(1))),
            'top1_agreement_independent_patterns':float(np.mean(outputs[independent].argmax(1)==ref[independent].argmax(1))),
            'mean_top5_set_overlap':float(np.mean([len(set(a)&set(b))/5 for a,b in zip(ref_top5,quant_top5)])),
            'reference_top1_in_quantized_top5':float(np.mean([int(a in b) for a,b in zip(ref.argmax(1),quant_top5)])),
            'shared_controls':['silence','sine_440'],
            'per_pattern_max_abs_error':err.max(1).tolist(),
            'float_parity':json.loads((HERE/'float_metrics.json').read_text()),
            'limitation':'Synthetic numerical validation only; no labelled AudioSet accuracy or real-sound generalization established.'}
    (HERE/'conversion_metrics.json').write_text(json.dumps(report,indent=2)+'\n')
    np.savez(HERE/'evaluation_quantized.npz',scores=outputs)
    write_firmware_fixtures(evaluation, outputs, args.firmware_cases)
    document=yaml.safe_load((HERE/'network.yml').read_text());document['network']['quantization']['error']=report
    (HERE/'network.yml').write_text('# Copyright 2026 Arm Limited and/or its affiliates.\n# SPDX-License-Identifier: Apache-2.0\n'+yaml.safe_dump(document,sort_keys=False))
    program=torch.export.export(quantized,example)
    save_quantized_program(program,spec.target,project.parent,network)
    print(json.dumps(report,indent=2),flush=True)

if __name__=='__main__':main()
