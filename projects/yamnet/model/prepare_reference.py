"""Generate original Keras references and exact frontend assets (host-only TF)."""
from pathlib import Path
import os, sys, json
os.environ['TF_ENABLE_ONEDNN_OPTS']='0'
os.environ['TF_CPP_MIN_LOG_LEVEL']='2'
import numpy as np
import tensorflow as tf
import tf_keras
import torch
from patterns import waveforms, features
from model import YAMNet
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE/'upstream'))
import params, yamnet, features as tf_features


def array(name, values, ctype='float'):
    flat=np.asarray(values).ravel()
    body=',\n'.join('  '+', '.join(f'{float(v):.9e}f' for v in flat[i:i+8]) for i in range(0,len(flat),8))
    return f'static const {ctype} {name}[{len(flat)}] = {{\n{body}\n}};\n'


def main():
    torch.set_num_threads(1)
    tf.config.threading.set_intra_op_parallelism_threads(1)
    tf.config.threading.set_inter_op_parallelism_threads(1)
    cfg=params.Params()
    inp=tf_keras.layers.Input(shape=(96,64))
    scores, emb=yamnet.yamnet(inp,cfg)
    ref=tf_keras.Model(inp,[scores,emb]);ref.load_weights(str(HERE/'upstream/yamnet.h5'))
    hann=tf.signal.hann_window(400,periodic=True).numpy()
    mel=tf.signal.linear_to_mel_weight_matrix(64,257,16000,125,7500).numpy()
    np.savez(HERE/'frontend_tables.npz',hann=hann,mel=mel)
    (HERE/'frontend_tables.h').write_text('// Copyright 2026 Arm Limited and/or its affiliates.\n// SPDX-License-Identifier: Apache-2.0\n// Generated by prepare_reference.py from TensorFlow signal operators.\n#pragma once\n'+array('yamnet_hann',hann)+array('yamnet_mel_weights',mel.T))
    # A compact independent firmware frontend fixture, from exact int16 PCM.
    pcm = np.round(next(w for n,w in waveforms(19429,3) if n=='white_noise')[:400]*32767).astype(np.int16)
    wave = pcm.astype(np.float32)/32768
    expected, _ = tf_features.waveform_to_log_mel_spectrogram_patches(wave,cfg)
    pcm_body=', '.join(str(int(v)) for v in pcm)
    (HERE/'frontend_test_data.h').write_text('// Copyright 2026 Arm Limited and/or its affiliates.\n// SPDX-License-Identifier: Apache-2.0\n// Generated using pinned TensorFlow features.py on normalized int16 PCM.\n#pragma once\n#include <stdint.h>\nstatic const int16_t yamnet_frontend_test_pcm[400] = {'+pcm_body+'};\n'+array('yamnet_frontend_test_expected',expected.numpy()[0]))
    model=YAMNet().eval()
    report={'reference_commit':json.loads((HERE/'upstream/provenance.json').read_text())['commit'],'tensorflow':tf.__version__,'tf_keras':tf_keras.__version__,'torch':torch.__version__}
    for split,seed,n in [('calibration',51773,96),('evaluation',19429,40)]:
        xs=[];ys=[];es=[];names=[];max_f=0;max_e=0;max_front=0
        for name,wave in waveforms(seed,n):
            x=features(wave,hann,mel)
            _,tf_x=tf_features.waveform_to_log_mel_spectrogram_patches(wave,cfg)
            max_front=max(max_front,float(np.max(np.abs(tf_x.numpy()-x))))
            # Classifier parity uses identical reference frontend inputs.
            x=tf_x.numpy()
            y,e=ref(x,training=False)
            with torch.no_grad():
                py=model(torch.from_numpy(x));pe=model.embedding(torch.from_numpy(x))
            max_f=max(max_f,float(np.max(np.abs(y.numpy()-py.numpy()))))
            max_e=max(max_e,float(np.max(np.abs(e.numpy()-pe.numpy()))))
            xs.append(x[0]);ys.append(y.numpy()[0]);es.append(e.numpy()[0]);names.append(name)
        np.savez(HERE/f'{split}_reference.npz',inputs=np.array(xs),scores=np.array(ys),embeddings=np.array(es),names=names)
        report[split]={'patterns':n,'float_score_max_abs_error':max_f,'float_embedding_max_abs_error':max_e,'numpy_frontend_max_abs_error':max_front}
        print(split,report[split],flush=True)
        assert max_f<2e-4 and max_e<2e-4
    (HERE/'float_metrics.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2),flush=True)

if __name__=='__main__':main()
