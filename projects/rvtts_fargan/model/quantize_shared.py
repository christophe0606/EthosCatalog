"""Calibrate a16w8 kernels and check exact scan/tile orchestration and PTQ."""
import argparse
from dataclasses import replace
import json
from pathlib import Path
import sys
import numpy as np
import torch
import yaml
from shared_model import HERE, BATCH, HALO, TILE, method_models, run_methods, sample
def metrics(a,b):
    d=np.asarray(a)-np.asarray(b)
    return {"max_absolute_error":float(np.max(np.abs(d))),"mean_absolute_error":float(np.mean(np.abs(d))),"rmse":float(np.sqrt(np.mean(d*d))),"reference_rms":float(np.sqrt(np.mean(np.asarray(a)**2)))}
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from project_config import DEFAULT_SOLUTION, selected_project
from quantized_model import compile_spec, save_quantized_program, method_configs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solution", type=Path, default=DEFAULT_SOLUTION)
    parser.add_argument("--project", default="rvtts_fargan")
    args = parser.parse_args()
    _, solution, project, config, network = selected_project(args.solution, args.project)
    if project.parent != HERE.parent:
        parser.error("This quantizer owns rvtts_fargan")
    torch.set_num_threads(1)
    models = method_models()
    calibration = {name: [] for name in models}
    with torch.no_grad():
        for i, frames in enumerate((1, 7, 32, 64, 96, 128, 173, 223)):
            run_methods(models, *sample(300+i, frames), capture=calibration)
    heldout = {name: [] for name in models}
    reference_sequences = []
    with torch.no_grad():
        for i, frames in enumerate((2, 19, 81, 157)):
            data = sample(800+i, frames)
            features, head = run_methods(models, *data, capture=heldout)
            reference_sequences.append((data, features, head))
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_a16w8_quantization_config
    from torchao.quantization.pt2e.quantize_pt2e import prepare_pt2e, convert_pt2e
    from torchao.quantization.pt2e.observer import MinMaxObserver
    spec = compile_spec(solution, project.parent, network)
    quantized, result, fixtures = {}, {}, {}
    header = ["// Copyright 2026 Arm Limited and/or its affiliates.", "// SPDX-License-Identifier: Apache-2.0",
              "// Generated by model/quantize.py; deterministic held-out kernel fixtures.", "#pragma once",
              f"#define RVTTS_BATCH {BATCH}", f"#define RVTTS_HALO {HALO}", f"#define RVTTS_TILE {TILE}"]
    for name, model in models.items():
        example = (calibration[name][0],)
        gm = torch.export.export(model, example).module(check_guards=False)
        # Retain the supplied per-tensor weight grid; per-channel requantizing
        # already-int8 weights adds avoidable rounding error.
        qconfig = get_symmetric_a16w8_quantization_config(is_per_channel=False, epsilon=2**-24)
        activation = replace(qconfig.input_activation, observer_or_fake_quant_ctr=MinMaxObserver.with_args(eps=2**-24))
        qconfig = replace(qconfig, input_activation=activation, output_activation=activation)
        q = EthosUQuantizer(spec).set_global(qconfig)
        prepared = prepare_pt2e(gm, q)
        with torch.no_grad():
            for x in calibration[name]:
                prepared(x)
            for observer in prepared.modules():
                if isinstance(observer, MinMaxObserver) and observer.dtype == torch.int16:
                    observer.min_val.mul_(1.1)
                    observer.max_val.mul_(1.1)
        converted = convert_pt2e(prepared, fold_quantize=True)
        ep = torch.export.export(converted, example)
        save_quantized_program(ep, spec.target, project.parent, method_configs(network)[name])
        quantized[name] = converted
        with torch.no_grad():
            refs = [model(x).numpy().reshape(-1) for x in heldout[name]]
            values = [converted(x).numpy().reshape(-1) for x in heldout[name]]
        result[name] = {"calibration_calls": len(calibration[name]), "evaluation_calls": len(heldout[name]),
                        **metrics(np.concatenate(refs), np.concatenate(values))}
        x = heldout[name][min(3, len(heldout[name])-1)]
        y = converted(x).detach()
        fixtures[name+"_input"] = x.numpy()
        fixtures[name+"_expected"] = y.numpy()
        scales = [float(n.args[1]) for n in ep.graph.nodes if n.target == torch.ops.quantized_decomposed.quantize_per_tensor.default]
        output_scale = scales[-1]
        result[name]["output_quantization_scale"] = output_scale
        header.append(f"#define RVTTS_{name.upper()}_ATOL {max(4*output_scale, 1e-5):.9e}f")
        for suffix, array in (("input", x.numpy()), ("expected", y.numpy())):
            vals = ",".join(f"{float(v):.9e}f" for v in array.reshape(-1))
            header.append(f"static const float rvtts_{name}_{suffix}[{array.size}] = {{{vals}}};")
        print(name, result[name], flush=True)
    sequences = []
    with torch.no_grad():
        for data, features, head in reference_sequences:
            qfeatures, qhead = run_methods(quantized, *data)
            sequences.append({"frames": len(data[0]), "features": metrics(features.numpy(), qfeatures.numpy()),
                              "prosody": metrics(head[:, :3].numpy(), qhead[:, :3].numpy()),
                              "finite": bool(torch.isfinite(qfeatures).all())})
    report = {"scheme": "symmetric int16 activations and per-tensor int8 weights, PTQ; no training",
              "reference": "PyTorch reconstruction of supplied int8-weight/float-activation C",
              "original_quantization_error": "trained float weights and error are not supplied by upstream",
              "calibration": "8 synthetic phoneme/word sequences, 1 to 223 frames; MinMax with 10% range guard",
              "evaluation": "4 independently seeded synthetic sequences, 2/19/81/157 frames",
              "methods": result, "closed_loop_sequences": sequences,
              "limitation": "Synthetic features do not establish speech quality; speaker listening validation is required."}
    (HERE / "conversion_metrics.json").write_text(json.dumps(report, indent=2)+"\n")
    (HERE / "model_test_data.h").write_text("\n".join(header)+"\n")
    np.savez(HERE / "quantized_fixtures.npz", **fixtures)
    content = yaml.safe_load(config.read_text())
    content["network"]["quantization"]["error"] = report
    config.write_text(yaml.safe_dump(content, sort_keys=False))
    print("closed_loop", sequences, flush=True)


if __name__ == "__main__":
    main()
