"""Prepare bounded CPU FARGAN storage and source-derived synthesis bodies.

Large float source matrices are requantized per output row to signed int16.
This is independent of the earlier int8 NPU FARGAN experiment. Runtime inputs
are dynamically scaled to int16 and raw dot products use signed 64-bit sums.
"""
from pathlib import Path
import json
import re
import zlib
import numpy as np
from model import HERE, load_arrays

PROJECT = HERE.parent
# Largest hot GRU input matrices, each evaluated four times per 160-sample frame.
# Keep below 600 KiB so ordinary DTCM retains margin for RTX/node state.
DTCM_MATRICES = {"sig_net_gru1_input", "sig_net_gru2_input", "sig_net_gru3_input"}


def function(text, name):
    m = re.search(r"(?:static )?void " + name + r"\(", text)
    start = text.index("{", m.start())
    depth, end = 1, start + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[m.start():end]


def main():
    arrays = load_arrays()
    original = (HERE / "upstream/fargan_data.c").read_text()
    layers = re.findall(r"linear_init\(&model->(\w+), arrays, (.*?), (\d+), (\d+)\)", original)
    cold, hot = bytearray(), bytearray()

    def append(array, dtcm=False):
        storage = hot if dtcm else cold
        storage.extend(bytes((-len(storage)) % 32))
        off = len(storage)
        storage.extend(array.tobytes())
        return f"{'cpu_hot_cache' if dtcm else 'cpu_cache'}+{off}"

    assigns, metrics = [], {}
    for name, _, inputs, outputs in layers:
        ni, no = int(inputs), int(outputs)
        weights = arrays[name + "_weights_float"].reshape(ni, no)
        if name == "cond_net_pembed":
            off = append(weights.astype("<f4"))
            assigns.append(f"m->{name}.float_weights=(const float*)({off});")
        else:
            rows = weights.T.copy()
            scale = np.maximum(np.max(np.abs(rows), axis=1) / np.float32(32760), np.float32(1e-30))
            quant = np.rint(rows / scale[:, None]).astype("<i2")
            # [row_group, column_block, row_in_group, eight adjacent columns].
            # Full row groups share one sequential weight cursor. A final
            # incomplete row group stays row-major, without padding/overreads.
            assert ni % 8 == 0
            groups = no // 4
            packed = np.concatenate((
                quant[:groups*4].reshape(groups, 4, ni//8, 8).transpose(0, 2, 1, 3).ravel(),
                quant[groups*4:].ravel(),
            )).astype("<i2")
            # Explicitly prove packing is a permutation of the same row values.
            restored = packed[:groups*4*ni].reshape(groups, ni//8, 4, 8).transpose(0, 2, 1, 3).reshape(groups*4, ni)
            assert np.array_equal(restored, quant[:groups*4])
            off = append(packed, name in DTCM_MATRICES)
            so = append(scale.astype("<f4"))
            assigns.append(f"m->{name}.weights=(const int16_t*)({off}); m->{name}.scale=(const float*)({so});")
            metrics[name] = dict(inputs=ni, outputs=no, storage="DTCM" if name in DTCM_MATRICES else "SRAM0", weight_bytes=packed.nbytes,
                                 max_weight_error=float(np.max(np.abs(rows - quant * scale[:, None]))))
        if name + "_bias" in arrays:
            off = append(arrays[name + "_bias"].astype("<f4"))
            assigns.append(f"m->{name}.bias=(const float*)({off});")
        assigns.append(f"m->{name}.nb_inputs={ni}; m->{name}.nb_outputs={no};")
    cold.extend(bytes((-len(cold)) % 32))
    hot.extend(bytes((-len(hot)) % 32))
    assert len(hot) <= 600*1024
    payload = cold + hot
    (HERE / "fargan_cpu_weights.bin").write_bytes(payload)
    header = ("// Copyright 2026 Arm Limited and/or its affiliates.\n// SPDX-License-Identifier: Apache-2.0\n"
              "// Generated by model/prepare_cpu.py from preserved BSD source arrays.\n#pragma once\n"
              f"#define RVTTS_FARGAN_CPU_CRC32 0x{zlib.crc32(payload):08x}u\n"
              "static void assign_model(FARGAN *m) {\n" + "\n".join(assigns) + "\n}\n")
    (PROJECT / "nodes_impl/fargan_cpu_data.h").write_text(header)
    (PROJECT / "nodes_impl/fargan_cpu_size.h").write_text(
        "// Copyright 2026 Arm Limited and/or its affiliates.\n// SPDX-License-Identifier: Apache-2.0\n"
        f"#pragma once\n#define RVTTS_FARGAN_CPU_BYTES {len(payload)}u\n"
        f"#define RVTTS_FARGAN_CPU_SRAM_BYTES {len(cold)}u\n"
        f"#define RVTTS_FARGAN_CPU_DTCM_BYTES {len(hot)}u\n")
    body = "// Generated by model/prepare_cpu.py. Original BSD notices follow.\n"
    for filename in ("nnet.c", "fargan.c"):
        source = (HERE / "upstream" / filename).read_text()
        body += source[:source.index("#")] + "\n"
    notices = body
    for filename in ("fargan_data.h", "fargan.h"):
        body += re.sub(r"^#include.*$", "", (HERE / "upstream" / filename).read_text(), flags=re.M) + "\n"
    (PROJECT / "nodes_impl/fargan_cpu_types.inc").write_text(body)
    body = notices
    nnet, fargan = [(HERE / "upstream" / n).read_text() for n in ("nnet.c", "fargan.c")]
    for name in ("compute_generic_dense", "compute_generic_gru", "compute_glu", "compute_generic_conv1d"):
        body += function(nnet, name) + "\n"
    for name in ("compute_fargan_cond", "fargan_deemphasis", "run_fargan_subframe", "fargan_cont", "fargan_synthesize_impl"):
        text = function(fargan, name)
        # The source reserves 10000 floats, but the concatenation's exact size
        # is 160+128+128+192+40+40 = 688. Bound this project-owned adaptation.
        text = text.replace("float skip_cat[10000];", "float skip_cat[688]; /* exact concatenation bound */")
        body += text + "\n"
    (PROJECT / "nodes_impl/fargan_cpu_synthesis.inc").write_text(body)
    result = dict(format="int16 matrices packed [four-row-group,column-block8,row-in-group,lane8]; final partial rows row-major; float32 per-row scales/biases/embedding; 32-byte alignment; cold SRAM payload then hot DTCM payload",
                  source="upstream/fargan_data.c float arrays", bytes=len(payload), crc32=f"{zlib.crc32(payload):08x}",
                  sram_bytes=len(cold), dtcm_bytes=len(hot), dtcm_payload_offset=len(cold), matrices=metrics)
    (HERE / "cpu_storage.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({k:v for k,v in result.items() if k != "matrices"}, indent=2), flush=True)


if __name__ == "__main__":
    main()
