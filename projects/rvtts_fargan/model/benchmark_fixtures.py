"""Generate benchmark-only complete-schedule float references; no cache changes."""
import importlib.util
from pathlib import Path
import numpy as np
import torch
from model import Fargan, FarganInit, frame_input, pitch_indices, STATE

HERE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location("shared_rvtts",HERE.parents[1]/"rvtts_lpc/model/model.py")
shared=importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)

def declaration(name,array,ctype):
    values=[f"{float(x):.9e}f" if ctype=="float" else str(int(x)) for x in np.asarray(array).reshape(-1)]
    rows=[",".join(values[i:i+16]) for i in range(0,len(values),16)]
    return f"static const {ctype} {name}[{len(values)}]={{\n"+",\n".join(rows)+"\n};"

def waveform(features,models):
    f=features.copy()
    p=f[:,18]
    f[:,18]=np.clip((p-p.mean())/max(float(p.std()),1e-5),-2.5,2.5)*.3615+.2120
    x,previous=frame_input(f[0])
    state=models[0](x,pitch_indices(previous),torch.zeros(1,STATE))
    memory=np.float32(0)
    pcm=[]
    for t in range(len(f)+2):
        x,period=frame_input(f[min(t,len(f)-1)])
        output=models[1](torch.cat((x,state),1),pitch_indices(previous))
        state=output[:,160:]
        previous=period
        for j,excitation in enumerate(output[0,:160].numpy()):
            memory=np.float32(excitation+np.float32(.85)*memory)
            if (t==0 and j<80) or (t==len(f)+1 and j>=80): continue
            pcm.append(np.float32(np.clip(memory,-1,32767/32768)))
    return np.asarray(pcm)

def main():
    torch.set_num_threads(1)
    models=(FarganInit().eval(),Fargan().eval())
    feature_models=shared.method_models()
    lines=["// Copyright 2026 Arm Limited and/or its affiliates.","// SPDX-License-Identifier: Apache-2.0",
           "// Generated by benchmark_fixtures.py; float source-model PCM, including flush/delay.","#pragma once","#include <cstdint>"]
    with torch.no_grad():
        for n,seed in ((2,800),(19,801),(81,802)):
            data=shared.sample(seed,n)
            features,_=shared.run_methods(feature_models,*data)
            pcm=waveform(features.numpy(),models)
            for suffix,array,ctype in (("phones",data[0],"uint8_t"),("stress",data[1],"uint8_t"),("words",data[2],"uint16_t"),("features",features.numpy(),"float"),("pcm",pcm,"float")):
                lines.append(declaration(f"rvtts_sequence_{n}_{suffix}",array,ctype))
    (HERE/"benchmark_inputs.h").write_text("\n".join(lines)+"\n",encoding="utf-8")

if __name__=="__main__": main()
